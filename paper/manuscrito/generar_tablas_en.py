"""Tablas del manuscrito en inglés, leídas de paper/tablas/*.csv (las genera analisis_paper.py).

    python3 paper/manuscrito/generar_tablas_en.py

Escribe paper/manuscrito/tablas/*.tex. No calcula nada: solo traduce y da formato,
para que cada número del manuscrito venga del pipeline.
"""
import csv, os

SRC = "paper/tablas"
DST = "paper/manuscrito/tablas"
CELLS = ["D10 5k", "D10 50k", "D10 500k", "D50 5k", "D50 50k", "D50 500k"]
HEAD = " & ".join(CELLS)
CLASS = {"unimodal": "Unimodal", "multimodal": "Multimodal", "hibrida": "Hybrid",
         "composicion": "Composition"}


def rows(name):
    with open(f"{SRC}/{name}.csv", newline="") as fh:
        return list(csv.DictReader(fh))


def write(name, body):
    os.makedirs(DST, exist_ok=True)
    with open(f"{DST}/{name}.tex", "w") as fh:
        fh.write(f"% Generated by generar_tablas_en.py from {SRC}; do not edit by hand.\n")
        fh.write(body)


def table(label, caption, colspec, header, lines, note=None, size="\\small"):
    out = [f"\\begin{{table}}[t]\n\\centering\n{size}\n\\caption{{{caption}}}\n\\label{{{label}}}",
           f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{header} \\\\\n\\midrule"]
    out += [l + " \\\\" for l in lines]
    out.append("\\bottomrule\n\\end{tabular}")
    if note:
        out.append(f"\\par\\smallskip\\footnotesize {note}")
    out.append("\\end{table}\n")
    return "\n".join(out)


def tex_p(s):
    """p-values as printed by the pipeline ('<1e-15', '2.19e-12', '0.032', '+'/'-' marks)."""
    sign = ""
    if s.endswith(("+", "-")) and not s.endswith("e-"):
        s, sign = s[:-1], s[-1]
    if s.startswith("<"):
        v = s[1:]
        m, e = v.split("e")
        txt = f"$<10^{{{int(e)}}}$" if m == "1" else f"$<{m}\\times10^{{{int(e)}}}$"
    elif "e" in s:
        m, e = s.split("e")
        txt = f"${m}\\times10^{{{int(e)}}}$"
    else:
        txt = s
    return txt + ({"+": "$^{+}$", "-": "$^{-}$"}[sign] if sign else "")


# ---- Table: mean Friedman ranks (t1) -------------------------------------------
def ranks():
    R = rows("t1_rangos_agregados")
    algs = [r for r in R if r["Algoritmo"] not in ("Friedman p", "CD Nemenyi")]
    best = {c: min(float(r[c].split()[0]) for r in algs) for c in CELLS}
    lines = []
    for r in algs:
        cells = []
        for c in CELLS:
            v, pos = r[c].split()
            cells.append(f"\\textbf{{{v}}} {pos}" if float(v) == best[c] else f"{v} {pos}")
        lines.append(" & ".join([r["Algoritmo"]] + cells))
    write("tab_ranks", table(
        "tab:ranks", "Mean Friedman ranks over the 71 functions, with positions in parentheses.",
        "l" + "r" * 6, "Algorithm & " + HEAD, lines,
        note="Ranks use the mean error of 51 runs. The best rank in each column is in bold. "
             "The Friedman test gives $p < 10^{-15}$ in every column, and the critical "
             "difference of the Nemenyi test is 1.61."))


# ---- Table: W/T/L (t7) and signed-rank with Holm (t9) --------------------------
def pairwise():
    W = rows("t7_wtl")
    S = {r["Competidor"]: r for r in rows("t9_signed_rank")}
    lines = []
    for r in W:
        c = r["Competidor"]
        lines.append(" & ".join([c] + [r[k] for k in CELLS]))
    write("tab_wtl", table(
        "tab:wtl", "Wins, ties, and losses of MAREA-2 against each competitor over the 71 functions.",
        "l" + "c" * 6, "Competitor & " + HEAD, lines,
        note="Per function, Wilcoxon rank-sum test on 51 runs with $\\alpha = 0.05$; the sign of a "
             "significant difference is given by the means."))
    lines = []
    for r in W:
        c = r["Competidor"]; s = S[c]
        cells = []
        for k in CELLS:
            rp, rn = s[f"{k} R+/R-"].split("/")
            p = s[f"{k} p Holm"]
            pv = 0.0 if p.startswith("<") else float(p)
            mark = "" if pv >= 0.05 else ("$^{+}$" if int(rp) > int(rn) else "$^{-}$")
            cells.append(tex_p(p) + mark)
        lines.append(" & ".join([c] + cells))
    write("tab_signedrank", table(
        "tab:signedrank", "Holm-adjusted $p$-values of the Wilcoxon signed-rank test between "
        "MAREA-2 and each competitor.",
        "l" + "c" * 6, "Competitor & " + HEAD, lines,
        note="The test pairs the 71 mean errors. $^{+}$ and $^{-}$ mark a significant difference "
             "($\\alpha = 0.05$) in favor of or against MAREA-2.", size="\\footnotesize"))


# ---- Table: W/T/L by function class against L-SHADE and jSO (t8) ---------------
def by_class():
    lines = []
    for r in rows("t8_wtl_por_clase"):
        if r["Competidor"] not in ("L-SHADE", "jSO"):
            continue
        lines.append(" & ".join([r["Competidor"], f"{CLASS[r['Clase']]} ({r['n']})"]
                                + [r[k] for k in CELLS]))
    write("tab_class", table(
        "tab:class", "Wins, ties, and losses of MAREA-2 against L-SHADE and jSO by function class.",
        "ll" + "c" * 6, "Competitor & Class ($n$) & " + HEAD, lines, size="\\footnotesize",
        note="Same test as Table~\\ref{tab:wtl}. The class follows the definitions of each suite."))


